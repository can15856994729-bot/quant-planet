// ── 将 Tushare industry 映射到申万一级行业 ───────────────────────────
export function mapToSWSector(tushareIndustry: string | null | undefined): SWSector {
  if (!tushareIndustry) return "未分类";
  // Normalize: strip whitespace, convert some traditional characters
  const normalized = tushareIndustry.trim()
    .replace(/銀/g, "银").replace(/藥/g, "药").replace(/長/g, "长");
  return TUSHARE_TO_SW[normalized] ?? "未分类";
}

// ── 行业分类统计结果 ──────────────────────────────────────────────────
export interface SectorGroup {
  name:        SWSector;
  stockCount:  number;
  symbols:     string[];     // tsCode 列表（前N只，完整列表在 API）
  color:       string;
  emoji:       string;
  desc:        string;
}

export interface ClassifyResult {
  sectors:            SectorGroup[];
  totalStocks:        number;
  classifiedStocks:   number;
  unclassifiedStocks: number;
}

// ── 将股票池按申万一级行业分组 ──────────────────────────────────────
export interface TushareStockRecord {
  ts_code:    string | number | null;
  symbol:     string | number | null;
  name:       string | number | null;
  industry:   string | number | null;
  list_status?: string | number | null;
  exchange?:  string | number | null;
  area?:      string | number | null;
  market?:    string | number | null;
  list_date?: string | number | null;
}

export function classifyStocks(records: TushareStockRecord[]): ClassifyResult {
  // Group by SW sector
  const groupMap = new Map<SWSector, string[]>();

  // Initialize all 31 sectors
  for (const sector of SW_SECTORS) {
    groupMap.set(sector, []);
  }
  groupMap.set("未分类", []);

  let classified = 0;

  for (const r of records) {
    const industry = String(r.industry ?? "");
    const sector   = mapToSWSector(industry);
    const tsCode   = String(r.ts_code ?? r.symbol ?? "");
    if (!tsCode) continue;

    const arr = groupMap.get(sector);
    if (arr) {
      arr.push(tsCode);
      if (sector !== "未分类") classified++;
    }
  }

  const sectors: SectorGroup[] = [];
  for (const [sectorName, syms] of groupMap.entries()) {
    const meta = SECTOR_META[sectorName] ?? SECTOR_META["未分类"]!;
    sectors.push({
      name:       sectorName,
      stockCount: syms.length,
      symbols:    syms.slice(0, 20), // return first 20 as sample
      color:      meta.color,
      emoji:      meta.emoji,
      desc:       meta.desc,
    });
  }

  // Sort: SW sector order first, then 未分类
  const swOrder = new Map(SW_SECTORS.map((s, i) => [s, i]));
  sectors.sort((a, b) => {
    const ai = swOrder.get(a.name as typeof SW_SECTORS[number]) ?? 999;
    const bi = swOrder.get(b.name as typeof SW_SECTORS[number]) ?? 999;
    if (ai !== bi) return ai - bi;
    return b.stockCount - a.stockCount;
  });

  const total = records.length;
  return {
    sectors,
    totalStocks:        total,
    classifiedStocks:   classified,
    unclassifiedStocks: total - classified,
  };
}

// ── 获取单只股票的申万行业 ───────────────────────────────────────────
export function getStockSWSector(tushareIndustry: string | null | undefined): SWSector {
  return mapToSWSector(tushareIndustry);
}

// ── 判断是否为 ST/＊ST 股票 ──────────────────────────────────────────
export function isST(name: string): boolean {
  return /^[\*＊]?ST/i.test(name.trim());
}

// ── 格式化行业标签 ────────────────────────────────────────────────────
export function getSectorTags(sector: SWSector, avgChange: number | null): string[] {
  const tags: string[] = [];
  if (avgChange != null) {
    if (avgChange > 2)    tags.push("领涨");
    else if (avgChange < -2) tags.push("弱势");
  }
  return tags;
}
